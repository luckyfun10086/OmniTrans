def _cp932_ok(ch):
    try:
        ch.encode("cp932")
        return True
    except UnicodeEncodeError:
        return False


# 仅保留目标可编码的映射（键是否可编码无所谓：可编码时映射根本不会触发）
S2J = {k: v for k, v in _S2J_RAW.items() if _cp932_ok(v)}


def convert(text):
    """简体 → CP932 可存储形式。返回 (转换文本, 丢失字符列表)。"""
    out, lost = [], []
    for ch in text:
        if _cp932_ok(ch):
            out.append(ch)
        elif ch in S2J:
            out.append(S2J[ch])
        elif ch == "\u3000" or ch.strip():
            lost.append(ch)
            out.append("？")
        else:                       # 空白类字符直接保留
            out.append(ch)
    return "".join(out), lost


