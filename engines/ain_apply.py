    tr = {k: v for k, v in tr.items() if isinstance(v, str) and v.strip()}
    if not tr:
        print("译文为空，无内容可回写")
        sys.exit(1)
    ains = find_ains(game)
    if not ains:
        print("未找到 .ain 文件")
        sys.exit(1)
    exe = ensure_tools()

    applied = mapped_entries = 0
    lost_total, lost_entries, lost_chars = 0, 0, []
    for ain in ains:
        with tempfile.TemporaryDirectory(dir=TOOL_DIR) as td:
            cur = os.path.join(td, "cur.txt")
            dump_text(exe, ain, cur)
            mod = os.path.join(td, "mod.txt")
            n_here = 0
            with open(mod, "w", encoding="utf-8", newline="\n") as mf:
                for kind, idx, text in parse_dump(cur):
                    val = tr.get(text)
                    if not val:
                        continue
                    conv, lost = convert(val)
                    if lost:
                        lost_entries += 1
                        lost_total += len(lost)
                        lost_chars += lost[:5]
                    if conv != val:
                        mapped_entries += 1
                    mf.write(f'{kind}[{idx}] = "{escape(conv)}"\n')
                    n_here += 1
            if not n_here:
                continue
            out_ain = os.path.join(td, "out.ain")
            p = subprocess.run([exe, "ain", "edit", "-t", mod, "-o", out_ain, ain],
                               capture_output=True)
            if p.returncode != 0 or not os.path.isfile(out_ain):
                print((p.stdout + p.stderr).decode("utf-8", "replace")[-400:])
                raise RuntimeError(f"{os.path.basename(ain)} 重建失败")
            # 回读验证：dump 重建文件，统计译文出现数
            chk = os.path.join(td, "chk.txt")
            dump_text(exe, out_ain, chk)
            dump_texts = {t for _k, _i, t in parse_dump(chk)}
            hit = sum(1 for _k, _i, t in parse_dump(cur)
                      if tr.get(t) and convert(tr[t])[0] in dump_texts)
            bak = ain + ".automt.bak"
            if not os.path.isfile(bak):
                import shutil
                shutil.copy2(ain, bak)
            import shutil
            shutil.move(out_ain, ain)
            applied += hit
            print(f"{os.path.basename(ain)}: 写入 {n_here} 条，回读验证 {hit} 条命中")

    print(f"合计回写 {applied} 条（字形映射 {mapped_entries} 条）")
